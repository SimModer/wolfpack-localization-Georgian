#include "addon.h"

static std::vector<std::string> lines(const std::string& text) {
    std::vector<std::string> out;
    size_t pos = 0;
    if (text.size() >= 3 && (unsigned char)text[0] == 0xEF && (unsigned char)text[1] == 0xBB && (unsigned char)text[2] == 0xBF) pos = 3;
    while (pos <= text.size()) {
        size_t e = text.find('\n', pos);
        if (e == std::string::npos) e = text.size();
        std::string l = text.substr(pos, e - pos);
        if (!l.empty() && l.back() == '\r') l.pop_back();
        out.push_back(l);
        pos = e + 1;
    }
    return out;
}

std::vector<AtEntry> parse_at(const std::string& text) {
    std::vector<AtEntry> out;
    for (auto& l : lines(text)) {
        if (l.empty() || l[0] == '#') continue;
        for (size_t i = 0; i < l.size(); ++i) {
            if (l[i] == '=' && (i == 0 || l[i - 1] != '\\')) {
                out.push_back({l.substr(0, i), l.substr(i + 1)});
                break;
            }
        }
    }
    return out;
}

std::string dump_at(const std::vector<AtEntry>& entries) {
    std::string o =
        "# Hard-coded texts of Wolfpack, translated at runtime by XUnity.AutoTranslator (needs BepInEx 6).\n"
        "# Format: English=Translation  (\\= is an '=', \\n a line break, r: lines are regular expressions)\n";
    for (auto& e : entries) o += e.src + "=" + e.dst + "\n";
    return o;
}

std::vector<std::string> parse_hardcoded(const std::string& text) {
    std::vector<std::string> out;
    for (auto& l : lines(text))
        if (!l.empty() && l[0] != '#') out.push_back(l);
    return out;
}

std::string at_escape(const std::string& s) {
    std::string o;
    for (size_t i = 0; i < s.size(); ++i) {
        if (s[i] == '=' && (i == 0 || s[i - 1] != '\\')) o += '\\';
        o += s[i];
    }
    return o;
}

std::string at_key(const std::string& s) {
    std::string o;
    for (char c : s) {
        if (c == '\r') continue;
        if (c == '\n') o += "\\n";
        else o += c;
    }
    return at_escape(o);
}

std::string at_config(const std::string& code, bool collect) {
    // "Passthrough" returns every text unchanged, so the plugin writes "text=text" to the OutputFile
    return std::string("[Service]\nEndpoint=") + (collect ? "Passthrough" : "NullTranslator") + "\nFallbackEndpoint=\n\n"
           "[General]\nLanguage=" + code + "\nFromLanguage=en\n\n"
           "[Files]\nDirectory=Translation\\{Lang}\\Text\nOutputFile=Translation\\{Lang}\\" +
           (collect ? "FoundTexts.txt" : "Text\\_AutoGeneratedTranslations.txt") + "\n\n"
           "[TextFrameworks]\nEnableUGUI=True\nEnableTextMeshPro=True\n\n"
           "[Behaviour]\nEnableSilentMode=True\n\n"
           "[Texture]\nTextureDirectory=Translation\\{Lang}\\Texture\nEnableTextureTranslation=True\n";
}
